def gen_factors_bulk_hook(spec: DiseaseSpec) -> str:
    k = spec.key
    Title = _capitalize(k)
    return f'''\'use client\'

import {{ useQuery, type UseQueryResult }} from \'@tanstack/react-query\'
import type {{ {Title}FactorsResponse }} from \'./use{Title}Factors\'

/**
 * One-shot bulk payload for the map tooltip layer — city + every zone +
 * every BKK district + non_bkk in a single HTTP round-trip. Auto-generated.
 */
export interface {Title}FactorsBulk {{
  city: {Title}FactorsResponse
  zones: Record<string, {Title}FactorsResponse>
  districts: Record<string, {Title}FactorsResponse>
  non_bkk: {Title}FactorsResponse
}}

export function use{Title}FactorsBulk(
  opts?: {{ enabled?: boolean }},
): UseQueryResult<{Title}FactorsBulk> {{
  return useQuery<{Title}FactorsBulk>({{
    queryKey: [\'v2\', \'{k}/factors/bulk\'],
    queryFn: async () => {{
      const res = await fetch(\'/api/v2/{k}/factors/bulk\')
      if (!res.ok) throw new Error(`HTTP ${{res.status}}`)
      const json = await res.json()
      return (json.data ?? json) as {Title}FactorsBulk
    }},
    staleTime: 10 * 60_000,
    enabled: opts?.enabled,
    retry: 1,
  }})
}}
'''


def gen_all_hooks(spec: DiseaseSpec) -> dict[str, str]:
    """Returns {filename: content} for the 3 hook files."""
    Title = _capitalize(spec.key)
    return {
        f"use{Title}Classification.ts": gen_classification_hook(spec),
        f"use{Title}Factors.ts":        gen_factors_hook(spec),
        f"use{Title}FactorsBulk.ts":    gen_factors_bulk_hook(spec),
    }
